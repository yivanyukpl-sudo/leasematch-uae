// A one-page PDF "sample confirmation" for the demo button on the payment
// step, so the flow can be tried without a real bank receipt. It is clearly
// marked as a sample and only ever attached inside LeaseMatch.

function esc(s: string): string {
  return s.replace(/[\\()]/g, (c) => `\\${c}`).replace(/[^\x20-\x7e]/g, "?");
}

export function sampleReceiptPdf(i: { side: "tenant" | "landlord"; property: string; amountAed: number; reference: string; payer: string; payee: string }): Buffer {
  const title = i.side === "tenant" ? "Proof of payment (SAMPLE)" : "Proof of receipt (SAMPLE)";
  const lines = [
    title,
    "",
    `Property: ${i.property}`,
    `Amount: AED ${i.amountAed.toLocaleString("en-US")}`,
    `From: ${i.payer}`,
    `To: ${i.payee}`,
    `Reference: ${i.reference}`,
    `Date: ${new Date().toISOString().slice(0, 10)}`,
    "",
    "Generated by the LeaseMatch UAE Functional MVP for demonstration.",
    "Not a real bank document.",
  ];
  const text = lines
    .map((l, n) => `BT /F1 ${n === 0 ? 18 : 12} Tf 72 ${760 - n * 22} Td (${esc(l)}) Tj ET`)
    .join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${Buffer.byteLength(text)} >>\nstream\n${text}\nendstream`,
  ];
  let out = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, n) => {
    offsets.push(Buffer.byteLength(out));
    out += `${n + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xref = Buffer.byteLength(out);
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  out += offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out);
}
