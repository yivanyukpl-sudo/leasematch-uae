// File uploads stored on local disk (UPLOAD_DIR — on Render, a folder on
// the persistent disk). Type is decided by the file's magic bytes, not the
// name or browser-supplied MIME, and names on disk are random ids.

import fs from "node:fs/promises";
import path from "node:path";
import { createUpload, newId, type Upload } from "./db";
import { sniffType } from "./file-type";

export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;

export function uploadDir(): string {
  return process.env.UPLOAD_DIR || path.join(process.cwd(), "data", "uploads");
}

export class UploadError extends Error {}

export async function saveUpload(
  file: File,
  input: { ownerId: string; propertyId: string | null; kind: Upload["kind"] }
): Promise<Upload> {
  if (file.size === 0) throw new UploadError("The file is empty");
  if (file.size > MAX_UPLOAD_BYTES) throw new UploadError("The file is larger than 10 MB");
  const buf = Buffer.from(await file.arrayBuffer());
  const type = sniffType(buf);
  // Payment confirmations may be PDFs (bank receipts); everything else is a photo.
  if (!type) throw new UploadError(input.kind === "payment_proof" ? "Only PDF, JPG, PNG or WebP files are allowed" : "Only JPG, PNG or WebP photos are allowed");
  if (type.mime === "application/pdf" && input.kind !== "payment_proof") throw new UploadError("Only JPG, PNG or WebP photos are allowed");

  const id = newId();
  const fileName = `${id}.${type.ext}`;
  await fs.mkdir(uploadDir(), { recursive: true });
  await fs.writeFile(path.join(uploadDir(), fileName), buf, { mode: 0o600 });

  return createUpload({
    id,
    owner_id: input.ownerId,
    property_id: input.propertyId,
    kind: input.kind,
    file_name: fileName,
    original_name: file.name ? file.name.slice(0, 200) : null,
    mime: type.mime,
    size: buf.length,
  });
}

export async function readUpload(upload: Upload): Promise<Buffer> {
  // file_name is generated by us, but never trust it to stay inside the dir.
  const full = path.join(uploadDir(), path.basename(upload.file_name));
  return fs.readFile(full);
}
